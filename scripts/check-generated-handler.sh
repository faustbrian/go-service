#!/usr/bin/env bash
set -euo pipefail

mode=${1:---check}
if [[ $# -gt 1 || ( "$mode" != --check && "$mode" != --write ) ]]; then
    printf 'usage: scripts/check-generated-handler.sh [--check|--write]\n' >&2
    exit 1
fi
repository=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
fixture="$repository/compatibility/testdata/generated-handler"
task=$(mktemp -d "${TMPDIR:-/tmp}/service-generated-handler.XXXXXX")
cleanup() {
    local status=$?
    trap - EXIT
    chmod -R u+w "$task" || status=1
    find "$task" -depth -delete || status=1
    exit "$status"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
mkdir -p "$task/build" "$task/mod" "$task/tmp"
export GOENV=off GOWORK=off GOTOOLCHAIN=local GOMAXPROCS=2 GOFLAGS=-p=1
export GOCACHE="$task/build" GOMODCACHE="$task/mod" GOTMPDIR="$task/tmp"
export GOPROXY=https://proxy.golang.org GOSUMDB=sum.golang.org
export GOPRIVATE='' GONOPROXY='' GONOSUMDB=''

# The generator is not an untrusted-spec sandbox. Refuse input drift before
# fetching or executing it, including extension/template injection surfaces.
python3 - "$fixture" <<'PY'
import hashlib, json, pathlib, sys
fixture = pathlib.Path(sys.argv[1])
record = json.loads((fixture / 'producer.json').read_text())
for item in record['inputs_sha256']:
    name, expected = item['path'], item['sha256']
    path = fixture / name
    if not path.is_file() or path.is_symlink() or hashlib.sha256(path.read_bytes()).hexdigest() != expected:
        raise SystemExit('generation input differs from reviewed producer record: ' + name)
spec = json.loads((fixture / 'openapi.json').read_text())
if (spec.get('openapi') != '3.0.3' or set(spec) != {'openapi', 'info', 'paths'}
        or spec['info'] != {'title': 'Finite Service handler fixture', 'version': '1.0.0'}
        or set(spec['paths']) != {'/generated-status'}
        or set(spec['paths']['/generated-status']) != {'get'}
        or spec['paths']['/generated-status']['get'] != {
            'operationId': 'getGeneratedStatus',
            'responses': {'200': {'description': 'The fixture is ready'}}}):
    raise SystemExit('generation is restricted to the finite reviewed operation')
if (fixture / 'codegen.yaml').read_text() != (
        'package: compatibility_test\ngenerate:\n  std-http-server: true\n'
        '  models: false\noutput: generated_handler_test.go\n'):
    raise SystemExit('generation configuration must not add templates or imports')
PY
cd "$task"
printf 'module generated-handler-tooling.test\n\ngo 1.27.0\n' > go.mod
test "$(go env GOVERSION)" = go1.27.2
go mod download -json github.com/oapi-codegen/oapi-codegen/v2@v2.8.0 > "$task/module.json"
python3 - "$fixture/producer.json" "$task/module.json" <<'PY'
import json, sys
record, module = (json.load(open(path)) for path in sys.argv[1:])
expected = {'Path': record['generator_module'], 'Version': record['version'],
            'Sum': record['module_sum'], 'GoModSum': record['go_mod_sum']}
if any(module.get(key) != value for key, value in expected.items()):
    raise SystemExit('authenticated public generator module differs from producer record')
if module.get('Origin', {}).get('Hash') != record['source_revision']:
    raise SystemExit('public generator source differs from immutable tag identity')
PY
go run github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0 \
    -config "$fixture/codegen.yaml" -o "$task/generated_handler_test.go" \
    "$fixture/openapi.json"

# Only stdlib generated code is admitted to this finite test fixture. This
# guard is intentionally not a general Go source or malicious-spec validator.
python3 - "$task/generated_handler_test.go" <<'PY'
import pathlib, re, sys
source_path = pathlib.Path(sys.argv[1])
source = source_path.read_text(encoding='utf-8')
upstream_header = '// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.8.0 DO NOT EDIT.'
if source.count(upstream_header) != 1:
    raise SystemExit('generator identity header differs')
imports = re.search(r'import\s*\((.*?)\)', source, re.S)
if not imports or set(re.findall(r'"([^"]+)"', imports.group(1))) - {'fmt', 'net/http'}:
    raise SystemExit('generated fixture has unexpected non-stdlib imports')
if re.search(r'\bfunc\s+init\s*\(', source) or '//go:linkname' in source or '//go:embed' in source:
    raise SystemExit('generated fixture contains unexpected initialization/directives')
# The tracked local driver owns this artifact. Attribute that real producer
# while retaining upstream identity; no generated declarations are modified.
local_header = ('// Code generated by ../scripts/check-generated-handler.sh; DO NOT EDIT.\n'
                '// Upstream generator: github.com/oapi-codegen/oapi-codegen/v2 v2.8.0.')
source_path.write_text(source.replace(upstream_header, local_header, 1), encoding='utf-8')
PY
if [[ "$mode" == --write ]]; then
    destination="$repository/compatibility/generated_handler_test.go"
    if [[ -L "$destination" || ( -e "$destination" && ! -f "$destination" ) ]]; then
        printf 'refusing nonregular generated fixture target\n' >&2
        exit 1
    fi
    cp "$task/generated_handler_test.go" "$destination"
else
    cmp "$task/generated_handler_test.go" "$repository/compatibility/generated_handler_test.go"
fi
printf 'pinned generated-handler %s passed\n' "$mode"
